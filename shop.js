productPixelTurntable?.addEventListener("pointerdown", (event) => {
  if (event.pointerType === "mouse" && event.button !== 0) return;
  rotationPointerId = event.pointerId;
  rotationStartX = event.clientX;
  rotationStartAngle = productRotation;
  productPixelTurntable.classList.add("is-dragging");
  productPixelTurntable.setPointerCapture(event.pointerId);
});

productPixelTurntable?.addEventListener("pointermove", (event) => {
  if (event.pointerId !== rotationPointerId) return;
  productRotation = rotationStartAngle + (event.clientX - rotationStartX) * 0.72;
  renderProductRotation();
});

const finishProductDrag = (event) => {
  if (event.pointerId !== rotationPointerId) return;
  productPixelTurntable?.classList.remove("is-dragging");
  if (productPixelTurntable?.hasPointerCapture(event.pointerId)) {
    productPixelTurntable.releasePointerCapture(event.pointerId);
  }
  rotationPointerId = null;
  rotationLastTime = performance.now();
};

productPixelTurntable?.addEventListener("pointerup", finishProductDrag);
productPixelTurntable?.addEventListener("pointercancel", finishProductDrag);

