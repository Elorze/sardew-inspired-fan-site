const readCart = () => {
  try {
    const savedCart = JSON.parse(localStorage.getItem(cartStorageKey) || "{}");
    return Object.fromEntries(
      Object.entries(savedCart).filter(
        ([productId, quantity]) =>
          shopCatalog[productId] && Number.isInteger(quantity) && quantity > 0,
      ),
    );
  } catch {
    return {};
  }
};

let cart = readCart();

