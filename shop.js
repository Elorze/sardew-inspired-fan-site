const playCheckoutBeep = () => {
  try {
    const AudioContext = window.AudioContext || window.webkitAudioContext;
    if (!AudioContext) return;
    checkoutAudioContext ||= new AudioContext();
    const oscillator = checkoutAudioContext.createOscillator();
    const gain = checkoutAudioContext.createGain();
    oscillator.type = "square";
    oscillator.frequency.value = 960;
    gain.gain.setValueAtTime(0.035, checkoutAudioContext.currentTime);
    gain.gain.exponentialRampToValueAtTime(
      0.001,
      checkoutAudioContext.currentTime + 0.07,
    );
    oscillator.connect(gain);
    gain.connect(checkoutAudioContext.destination);
    oscillator.start();
    oscillator.stop(checkoutAudioContext.currentTime + 0.07);
  } catch {
    // Checkout remains usable when browser audio is unavailable.
  }
};

const renderCheckoutReceipt = (entries, receiptCode) => {
  if (
    !checkoutReceipt ||
    !checkoutReceiptItems ||
    !checkoutReceiptCode ||
    !checkoutReceiptTotal
  ) {
    return;
  }

  checkoutReceiptItems.replaceChildren();
  let total = 0;
  entries.forEach(([productId, quantity]) => {
    const product = shopCatalog[productId];
    if (!product) return;
    total += product.price * quantity;
    const row = document.createElement("div");
    const name = document.createElement("span");
    const subtotal = document.createElement("span");
    name.textContent = `${product.shortName} × ${quantity}`;
    subtotal.textContent = formatPrice(product.price * quantity);
    row.append(name, subtotal);
    checkoutReceiptItems.append(row);
  });
  checkoutReceiptCode.textContent = receiptCode;
  checkoutReceiptTotal.textContent = formatPrice(total);
  checkoutReceipt.hidden = false;
  checkoutReceipt.classList.remove("is-printing");
  window.requestAnimationFrame(() => {
    checkoutReceipt.classList.add("is-printing");
  });
  if (checkoutDelivery) checkoutDelivery.hidden = false;
};

const startCheckoutScan = async ({ openOnComplete = false } = {}) => {
  const entries = Object.entries(cart);
  if (!entries.length || checkoutScanning || checkoutPending) return;

  const scanQueue = entries.flatMap(([productId, quantity]) =>
    Array.from({ length: quantity }, () => productId),
  );
  const runId = ++checkoutScanRun;
  checkoutScanning = true;
  checkoutReceiptReady = false;
  if (cartDrawer) cartDrawer.dataset.checkoutState = "scanning";
  if (checkoutReceipt) checkoutReceipt.hidden = true;
  if (checkoutScan) checkoutScan.hidden = false;
  marketRegister?.classList.remove("is-complete");
  marketRegister?.classList.add("is-scanning");
  if (marketRegisterStatus) marketRegisterStatus.textContent = "正在扫描";
  setPaymentStatus("收银台正在逐件扫描。");
  renderCart();

  for (let index = 0; index < scanQueue.length; index += 1) {
    if (runId !== checkoutScanRun) return;
    const product = shopCatalog[scanQueue[index]];
    if (!product) continue;
    if (checkoutScanImage) {
      checkoutScanImage.src = product.image;
      checkoutScanImage.alt = "";
    }
    if (checkoutScanStatus) {
      checkoutScanStatus.textContent =
        `${index + 1} / ${scanQueue.length}　${product.shortName}`;
    }
    if (marketRegisterItem) {
      marketRegisterItem.src = product.image;
      marketRegisterItem.alt = "";
    }
    if (marketRegisterStatus) {
      marketRegisterStatus.textContent = `${index + 1} / ${scanQueue.length}`;
    }
    playCheckoutBeep();
    await new Promise((resolve) => window.setTimeout(resolve, 430));
  }

  if (runId !== checkoutScanRun) return;
  const receiptCode = `ZZ-${Date.now().toString().slice(-8)}`;
  renderCheckoutReceipt(entries, receiptCode);
  if (checkoutScan) checkoutScan.hidden = true;
  checkoutScanning = false;
  checkoutReceiptReady = true;
  if (cartDrawer) cartDrawer.dataset.checkoutState = "receipt";
  marketRegister?.classList.remove("is-scanning");
  marketRegister?.classList.add("is-complete");
  if (marketRegisterStatus) marketRegisterStatus.textContent = "扫描完成";
  setPaymentStatus("扫描完成，小票已打印。");
  renderCart();
  if (openOnComplete) {
    window.setTimeout(openCart, reduceMotion.matches ? 0 : 260);
  }
};

