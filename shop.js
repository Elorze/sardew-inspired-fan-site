cartItems?.addEventListener("click", (event) => {
  const button = event.target instanceof Element
    ? event.target.closest("[data-cart-action]")
    : null;
  if (!(button instanceof HTMLButtonElement)) return;

  const productId = button.dataset.productId;
  const action = button.dataset.cartAction;
  if (!productId || !cart[productId]) return;

  if (action === "increase") cart[productId] += 1;
  if (action === "decrease") cart[productId] -= 1;
  if (action === "remove" || cart[productId] <= 0) delete cart[productId];

  clearCheckoutReceipt();
  saveCart();
  setPaymentStatus("");
  renderCart();
});

