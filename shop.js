const createQuantityButton = (label, symbol, productId, action) => {
  const button = document.createElement("button");
  button.type = "button";
  button.setAttribute("aria-label", label);
  button.dataset.productId = productId;
  button.dataset.cartAction = action;
  button.textContent = symbol;
  return button;
};

const renderCart = () => {
  if (!cartItems || !cartCount) return;

  cartItems.replaceChildren();
  const entries = Object.entries(cart);
  const totalQuantity = entries.reduce((total, [, quantity]) => total + quantity, 0);
  const totalPrice = entries.reduce(
    (total, [productId, quantity]) => total + shopCatalog[productId].price * quantity,
    0,
  );
  cartCount.value = totalQuantity ? String(totalQuantity) : "";
  cartCount.textContent = totalQuantity ? String(totalQuantity) : "";
  cartCount.hidden = totalQuantity === 0;
  if (cartTotal) cartTotal.textContent = formatPrice(totalPrice);
  if (checkoutButton) {
    checkoutButton.disabled = !entries.length || checkoutPending || checkoutScanning;
    checkoutButton.textContent = checkoutScanning
      ? "正在扫描…"
      : checkoutPending
        ? "正在连接支付宝…"
        : checkoutReceiptReady
          ? "确认并前往支付宝"
          : "扫描商品并结算";
  }

  if (!entries.length) {
    const emptyMessage = document.createElement("p");
    emptyMessage.className = "cart-empty";
    emptyMessage.textContent = "购物车还是空的";
    cartItems.append(emptyMessage);
    return;
  }

  entries.forEach(([productId, quantity]) => {
    const product = shopCatalog[productId];
    const item = document.createElement("article");
    item.className = "cart-item";

    const image = document.createElement("img");
    image.src = product.image;
    image.alt = "";

    const copy = document.createElement("div");
    copy.className = "cart-item-copy";

    const name = document.createElement("h3");
    name.textContent = product.name;

    const price = document.createElement("p");
    price.textContent = formatPrice(product.price);

    const controls = document.createElement("div");
    controls.className = "cart-quantity";
    controls.append(
      createQuantityButton(`减少${product.name}数量`, "−", productId, "decrease"),
    );

    const quantityOutput = document.createElement("output");
    quantityOutput.value = String(quantity);
    quantityOutput.textContent = String(quantity);
    quantityOutput.setAttribute("aria-label", `${product.name}数量`);
    controls.append(quantityOutput);
    controls.append(
      createQuantityButton(`增加${product.name}数量`, "+", productId, "increase"),
      createQuantityButton(`移除${product.name}`, "×", productId, "remove"),
    );

    copy.append(name, price, controls);
    item.append(image, copy);
    cartItems.append(item);
  });
};

