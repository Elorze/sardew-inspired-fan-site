const createAlipayCheckout = async () => {
  const items = Object.entries(cart).map(([productId, quantity]) => ({
    productId,
    quantity,
  }));
  if (!items.length || checkoutPending) return;
  if (!checkoutDelivery?.reportValidity()) {
    setPaymentStatus("请先填写完整的收货信息。");
    return;
  }

  const deliveryData = new FormData(checkoutDelivery);
  const delivery = {
    recipientName: deliveryData.get("recipientName"),
    phone: deliveryData.get("phone"),
    address: deliveryData.get("address"),
  };

  checkoutPending = true;
  if (cartDrawer) cartDrawer.dataset.checkoutState = "payment";
  setPaymentStatus("正在创建支付宝订单…");
  renderCart();

  try {
    const response = await fetch("/api/alipay/create-order", {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
      },
      body: JSON.stringify({ items, delivery }),
    });
    const result = await response.json().catch(() => ({}));
    if (!response.ok) {
      const error = new Error(result.message || "暂时无法创建支付宝订单。");
      error.code = [404, 405, 501].includes(response.status)
        ? "PAYMENT_SERVICE_UNAVAILABLE"
        : result.code || "CHECKOUT_FAILED";
      throw error;
    }

    const paymentUrl = new URL(result.paymentUrl);
    if (!["https:", "http:"].includes(paymentUrl.protocol)) {
      throw new Error("支付宝支付地址无效。");
    }

    sessionStorage.setItem("zhongzhong-pending-order", result.outTradeNo);
    window.location.assign(paymentUrl.href);
  } catch (error) {
    const message =
      error.code === "ALIPAY_NOT_CONFIGURED"
        ? "支付宝商户参数尚未配置，暂时不能付款。"
        : error.code === "PAYMENT_SERVICE_UNAVAILABLE" ||
            error instanceof TypeError
          ? "支付服务没有启动，请稍后再试。"
          : error.message || "支付宝连接失败，请稍后再试。";
    setPaymentStatus(message);
    showShopMessage(message, 3200);
  } finally {
    checkoutPending = false;
    if (cartDrawer && checkoutReceiptReady) {
      cartDrawer.dataset.checkoutState = "receipt";
    }
    renderCart();
  }
};

const waitForPaymentConfirmation = async (outTradeNo) => {
  openCart();
  setPaymentStatus("支付宝已返回，正在确认付款结果…");

  for (let attempt = 0; attempt < 12; attempt += 1) {
    try {
      const response = await fetch(
        `/api/alipay/orders/${encodeURIComponent(outTradeNo)}`,
        { cache: "no-store" },
      );
      const order = await response.json();
      if (response.ok && order.status === "paid") {
        cart = {};
        saveCart();
        checkoutDelivery?.reset();
        clearCheckoutReceipt();
        renderCart();
        setPaymentStatus("付款成功，订单已经确认。");
        showShopMessage("付款成功，订单已经确认", 3600);
        sessionStorage.removeItem("zhongzhong-pending-order");
        history.replaceState(null, "", "shop.html");
        return;
      }
      if (response.ok && order.status === "failed") {
        setPaymentStatus("订单创建失败，没有发生扣款。");
        history.replaceState(null, "", "shop.html");
        return;
      }
      if (
        response.ok &&
        ["closed", "expired", "review"].includes(order.status)
      ) {
        const message =
          order.status === "review"
            ? "订单信息需要人工核对，请不要重复支付。"
            : "订单已经关闭或超时，没有发生新的扣款。";
        setPaymentStatus(message);
        history.replaceState(null, "", "shop.html");
        return;
      }
    } catch {
      // The asynchronous notification may arrive after the browser return.
    }
    await new Promise((resolve) => window.setTimeout(resolve, 2000));
  }

  setPaymentStatus("付款结果仍在确认，请不要重复支付。");
};

const handlePaymentReturn = () => {
  const params = new URLSearchParams(window.location.search);
  const paymentState = params.get("payment");
  if (paymentState === "invalid") {
    openCart();
    setPaymentStatus("支付返回信息验证失败，请在支付宝账单中确认。");
    history.replaceState(null, "", "shop.html");
    return;
  }

  if (paymentState === "returned") {
    const outTradeNo = params.get("out_trade_no");
    if (outTradeNo) waitForPaymentConfirmation(outTradeNo);
  }
};

